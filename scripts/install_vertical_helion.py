"""Copy the hand-written vertical Helion kernels into the generated corpus.

    python scripts/install_vertical_helion.py [--status-only]

The kernels live in benchmarks/vertical_helion/new/<repro>/ (with a copy of
the repro they were written for), because regenerating mm_repro/ replaces the
whole tree. For every kernel whose repro still exists in
mm_repro/canonical/vertical/, helion_vertical.py (and its result, if the
repro's first shape is unchanged) is copied next to repro.py.
benchmarks/vertical_helion/STATUS.md lists, for every kernel, whether its
repro is in the corpus and why missing ones are gone. --status-only writes
STATUS.md without copying anything.
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STORE = ROOT / "benchmarks" / "vertical_helion" / "new"
CORPUS = ROOT / "mm_repro"


def reason(stored: Path, members: dict) -> str:
    points = json.loads((stored / "shapes.json").read_text())["points"]
    vertical = points[0]["partition_metrics"].get("vertical", {})
    big = [s for s in vertical.get("stages", []) if s["R"] > 128 or s["F"] > 128]
    if big:
        worst = ", ".join(f'{s["op"]} R={s["R"]} F={s["F"]}' for s in big)
        return f"not extracted: R/F above 128 ({worst})"
    pattern = json.loads((stored / "meta.json").read_text())["pattern_hash"]
    if pattern in members:
        return f"deduplicated into family representative {members[pattern]}"
    return "not extracted any more (region changed)"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--status-only", action="store_true")
    args = parser.parse_args()
    families = json.loads((CORPUS / "families.json").read_text())
    members = {
        m["pattern_hash"]: f["representative"]
        for f in families
        for m in f["members"]
        if m["pattern_hash"] != f["representative"]
    }
    rows = []
    for stored in sorted(p for p in STORE.iterdir() if (p / "helion_vertical.py").exists()):
        target = CORPUS / "canonical" / "vertical" / stored.name
        if target.is_dir():
            first = lambda d: json.loads((d / "shapes.json").read_text())["points"][0]["inputs"]
            same_shape = first(stored) == first(target)
            if not args.status_only:
                shutil.copy2(stored / "helion_vertical.py", target / "helion_vertical.py")
                if same_shape:
                    shutil.copy2(
                        stored / "helion_vertical_result.json",
                        target / "helion_vertical_result.json",
                    )
            if same_shape:
                rows.append((stored.name, "in mm_repro/canonical/vertical"))
            else:
                # The repro kept fewer shape points; the stored result is for the
                # old first shape, so the corpus copy needs its own run.
                extra = sorted(p.name for p in stored.glob("helion_vertical_result_*.json"))
                note = f" (re-measured: {', '.join(extra)})" if extra else ""
                rows.append(
                    (
                        stored.name,
                        "in mm_repro/canonical/vertical with fewer shape points; the "
                        "stored result is for its old first shape" + note,
                    )
                )
        else:
            rows.append((stored.name, reason(stored, members)))
    lines = [
        "# Vertical Helion kernels: where they are",
        "",
        "Generated by `python scripts/install_vertical_helion.py`, which also copies",
        "the kernels into the corpus. Every kernel stays runnable from",
        "`benchmarks/vertical_helion/{new,old}/<repro>/helion_vertical.py`.",
        "`old/` holds kernels for regions of the previous largest-window corpus.",
        "",
        "| repro | status |",
        "| --- | --- |",
        *(f"| `{name}` | {status} |" for name, status in rows),
        "",
    ]
    (STORE.parent / "STATUS.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
